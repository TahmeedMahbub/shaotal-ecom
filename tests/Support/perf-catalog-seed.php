<?php

/*
| LOCAL PERFORMANCE DATABASE ONLY. Prints SQL that adds a synthetic catalog on top of sql/local_test_seed.sql, so page
| weight and query behaviour can be measured at a realistic size. Never load it into the shared/production database.
|
|   php tests/Support/perf-catalog-seed.php [products=400] > /tmp/perf.sql
|   mysql -uroot -h127.0.0.1 shaotal_perf_test < /tmp/perf.sql      (after ecom.sql, google_login.sql, ci-schema-drift.sql, local_test_seed.sql)
|
| Deterministic (fixed seed): the same arguments always produce the same rows.
*/

mt_srand(20261112);
$count = (int) ($argv[1] ?? 400);
$q = fn ($s) => "'".str_replace(['\\', "'"], ['\\\\', "''"], $s)."'";

$images = ['sample.jpg', 'cld-sample.jpg', 'cld-sample-2.jpg', 'cld-sample-3.jpg', 'cld-sample-4.jpg', 'cld-sample-5.jpg'];
$img = fn ($i) => 'https://res.cloudinary.com/demo/image/upload/'.$images[$i % count($images)];
$words = ['Handwoven', 'Organic', 'Heritage', 'Artisan', 'Natural', 'Classic', 'Relaxed', 'Embroidered', 'Linen', 'Jute', 'Cotton', 'Kantha', 'Terracotta', 'Indigo', 'Sunset', 'Monsoon'];
$nouns = ['Tee', 'Shirt', 'Trousers', 'Cushion', 'Throw', 'Basket', 'Tote', 'Rug', 'Runner', 'Journal', 'Planter', 'Scarf', 'Kurta', 'Placemat', 'Lamp Shade'];
$colors = [['Olive Green', '#5C6B4F'], ['Midnight Black', '#1A1A1A'], ['Natural', '#D8C3A5'], ['Indigo', '#3F51B5'], ['Rust', '#B7410E']];
$sizes = ['S', 'M', 'L', 'XL'];
$lorem = 'Made by small artisan workshops using traditional techniques passed down through generations. Each piece is finished by hand, so small variations in colour and texture are part of its character. Thoughtfully packed and shipped within Australia. ';

echo "-- generated by tests/Support/perf-catalog-seed.php ({$count} products)\n";
echo "INSERT INTO subcategories (id,category_id,name,slug,sort_order) VALUES (4,1,'Shirts','shirts',3),(5,1,'Kurtas','kurtas',4),(6,2,'Throws','throws',2),(7,2,'Rugs','rugs',3),(8,3,'Bags','bags',1),(9,3,'Baskets','baskets',2),(10,4,'Stationery','stationery',1);\n";
$subsByCat = [1 => [1, 2, 4, 5], 2 => [3, 6, 7], 3 => [8, 9], 4 => [10]];

$colorId = 100;
$sizeId = 100;
$imageId = 100;
for ($i = 0; $i < $count; $i++) {
    $id = 100 + $i;
    $cat = [1, 1, 2, 2, 3, 4][$i % 6];
    $sub = $subsByCat[$cat][$i % count($subsByCat[$cat])];
    $name = $words[mt_rand(0, count($words) - 1)].' '.$words[mt_rand(0, count($words) - 1)].' '.$nouns[mt_rand(0, count($nouns) - 1)].' '.$id;
    $slug = strtolower(preg_replace('/[^a-z0-9]+/i', '-', $name));
    $price = mt_rand(19, 189) + 0.00;
    $selling = mt_rand(0, 3) === 0 ? round($price * 0.8, 2) : $price;
    $variants = $cat === 1 || ($cat === 2 && $i % 3 === 0);
    $availability = $i % 25 === 0 ? 'preorder' : ($i % 40 === 0 ? 'out_of_stock' : 'in_stock');
    $full = '<p>'.str_repeat($lorem, 3).'</p><ul><li>Hand finished</li><li>Natural fibres</li><li>Fair-trade workshop</li></ul>';
    echo sprintf(
        "INSERT INTO products (id,category_id,subcategory_id,brand_id,name,slug,sku,short_description,description,price,selling_price,has_variants,variant_scenario,stock_qty,availability,preorder_release_date,low_stock_threshold,visibility,status,badge) VALUES (%d,%d,%d,%d,%s,%s,%s,%s,%s,%.2f,%.2f,%d,%s,%s,%s,%s,5,'visible','active',%s);\n",
        $id, $cat, $sub, ($i % 2) + 1, $q($name), $q($slug), $q('PERF-'.$id), $q('Hand-finished '.strtolower($nouns[$i % count($nouns)]).' from an artisan workshop'), $q($full),
        $price, $selling, $variants ? 1 : 0, $variants ? "'color_size'" : 'NULL', $variants ? 'NULL' : (string) mt_rand(0, 30),
        $q($availability), $availability === 'preorder' ? "'2026-12-20'" : 'NULL', $i % 7 === 0 ? "'[\"new\"]'" : 'NULL'
    );
    echo sprintf("INSERT INTO product_specifications (product_id,material,care_instructions) VALUES (%d,'Natural fibre','Hand wash cold.');\n", $id);

    $imgRows = [];
    for ($k = 0; $k < 4; $k++) {
        $imgRows[] = sprintf('(%d,%d,%s,%d,%d)', $imageId++, $id, $q($img($i + $k)), $k === 0 ? 1 : 0, $k);
    }
    echo 'INSERT INTO product_images (id,product_id,image_url,is_main,sort_order) VALUES '.implode(',', $imgRows).";\n";

    if ($variants) {
        $c = [];
        $s = [];
        $v = [];
        foreach (array_slice($colors, 0, 3) as $ci => [$cn, $hex]) {
            $c[] = sprintf('(%d,%d,%s,%s,%d)', $colorId + $ci, $id, $q($cn), $q($hex), $ci);
        }
        foreach ($sizes as $si => $sl) {
            $s[] = sprintf('(%d,%d,%s,%d)', $sizeId + $si, $id, $q($sl), $si);
        }
        foreach (array_keys(array_slice($colors, 0, 3)) as $ci) {
            foreach (array_keys($sizes) as $si) {
                $v[] = sprintf("(%d,%d,%d,'PERF-%d-%d-%d',%d)", $id, $colorId + $ci, $sizeId + $si, $id, $ci, $si, mt_rand(0, 12));
            }
        }
        echo 'INSERT INTO product_colors (id,product_id,name,hex_code,sort_order) VALUES '.implode(',', $c).";\n";
        echo 'INSERT INTO product_sizes (id,product_id,size_label,sort_order) VALUES '.implode(',', $s).";\n";
        echo 'INSERT INTO product_variants (product_id,color_id,size_id,sku,stock_qty) VALUES '.implode(',', $v).";\n";
        $colorId += 3;
        $sizeId += 4;
    }
}
